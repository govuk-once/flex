type JiraIssue = {
  key: string;
  fields: {
    summary: string;
    labels: string[];
  };
};

type JiraSearchResponse = {
  issues: JiraIssue[];
};

type JiraCreateResponse = {
  id: string;
  key: string;
};

function requiredEnv(name: string): string {
  const value = process.env[name];

  if (!value) {
    throw new Error(`Missing environment variable: ${name}`);
  }

  return value;
}

const jiraUrl = requiredEnv("JIRA_URL").replace(/\/$/, "");
const jiraEmail = requiredEnv("JIRA_EMAIL");
const jiraToken = requiredEnv("JIRA_API_TOKEN");

const projectKey = "GUV";
const mockIssueKey = "GUOIT-202-MOCK-001";
const testLabel = "guoit-202-mock-001";

const auth = Buffer.from(`${jiraEmail}:${jiraToken}`).toString("base64");

async function jiraRequest(
  path: string,
  options: RequestInit = {},
): Promise<Response> {
  const headers = new Headers(options.headers);

  headers.set("Authorization", `Basic ${auth}`);
  headers.set("Accept", "application/json");
  headers.set("Content-Type", "application/json");

  const response = await fetch(`${jiraUrl}${path}`, {
    ...options,
    headers,
  });

  if (!response.ok) {
    const body = await response.text();

    throw new Error(`Jira API HTTP ${String(response.status)}: ${body}`);
  }

  return response;
}

async function findExistingTicket(): Promise<string | undefined> {
  const jql = `project = ${projectKey} AND labels = "${testLabel}"`;

  const url = new URL("/rest/api/3/search/jql", `${jiraUrl}/`);

  url.searchParams.set("jql", jql);
  url.searchParams.set("maxResults", "100");
  url.searchParams.set("fields", "summary,labels");

  const response = await jiraRequest(`${url.pathname}${url.search}`);

  const data = (await response.json()) as JiraSearchResponse;

  const existing = data.issues.find((issue) =>
    issue.fields.labels.includes(testLabel),
  );

  return existing?.key;
}

async function createTestTicket(): Promise<string> {
  const summary = "[TEST] SonarCloud HIGH security finding - FLEX";

  const description = [
    "AUTOMATED TEST - NOT A REAL SECURITY VULNERABILITY",
    "",
    "Test generated by GUOIT-202.",
    "",
    `SonarCloud issue key: ${mockIssueKey}`,
    "Organization: govuk-once",
    "Project: govuk-once_flex",
    "Severity: HIGH",
    "Component: libs/testing/src/mock-security.ts",
    "Rule: typescript:S0000",
    "",
    "Purpose:",
    "Validate Jira ticket creation and deduplication.",
    "",
    "This issue can be closed after testing.",
  ].join("\n");

  const payload = {
    fields: {
      project: {
        key: projectKey,
      },
      issuetype: {
        name: "Task",
      },
      summary,
      labels: ["sonarcloud", "security", "automation-test", testLabel],
      description: {
        type: "doc",
        version: 1,
        content: [
          {
            type: "paragraph",
            content: [
              {
                type: "text",
                text: description,
              },
            ],
          },
        ],
      },
    },
  };

  const response = await jiraRequest("/rest/api/3/issue", {
    method: "POST",
    body: JSON.stringify(payload),
  });

  const result = (await response.json()) as JiraCreateResponse;

  return result.key;
}

async function main(): Promise<void> {
  console.log("GUOIT-202 - Jira integration test");
  console.log(`Project: ${projectKey}`);
  console.log(`Mock issue: ${mockIssueKey}`);
  console.log("Mode: REAL TEST TICKET");

  console.log("Checking Jira for an existing ticket...");

  const existingKey = await findExistingTicket();

  if (existingKey) {
    console.log(`Existing Jira ticket: ${existingKey}`);
    console.log("Duplicate detected. No new ticket created.");
    return;
  }

  console.log("No existing ticket found.");
  console.log("Creating test Jira ticket...");

  const createdKey = await createTestTicket();

  console.log(`Created Jira ticket: ${createdKey}`);
  console.log(`URL: ${jiraUrl}/browse/${createdKey}`);
  console.log("Test completed successfully.");
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
